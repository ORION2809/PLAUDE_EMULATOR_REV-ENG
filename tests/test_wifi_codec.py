def test_file_record_is_u32_u32_u16_little_endian():
    rec = FileRecord(0x12345678, 0x100, 2)
    assert rec.pack() == bytes.fromhex("78563412" "00010000" "0200")
    assert parse_file_records(rec.pack()) == [rec]


def test_file_list_response_bytes_and_partial_record_tolerance():
    rec = FileRecord(0x12345678, 0x100, 2)
    wire = FileListResponse(uid=0, status=0, count=1, offset=0, records=[rec]).encode()
    body = b'{"uid":0,"status":0,"count":1,"offset":0}'
    assert len(body) == 41
    assert wire == bytes.fromhex("3b000001" "0b00" "2900") + body + rec.pack()
    # the Kotlin loop is `while (i + 10 <= len)`: a dangling 4 bytes are ignored
    dangling = wire + b"\x01\x02\x03\x04"
    rsp = decode_for_phone(dangling)
    assert isinstance(rsp, FileListResponse) and rsp.records == [rec]
    assert parse_file_records(b"\x00" * 9) == []
    assert pack_file_records([]) == b""


def test_session_id_doubles_as_unix_timestamp_in_the_phone_file_name():
    assert file_name_for_session(1700000000, timezone.utc) == "2023-11-14_22-13-20.opus"
    assert file_name_for_session(99) == "log99"
    assert file_name_for_session(100, timezone.utc) == "1970-01-01_00-01-40.opus"


