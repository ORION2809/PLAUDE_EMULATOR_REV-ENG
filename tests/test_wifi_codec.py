def test_aes_gcm_wiring_against_the_nist_vector():
    sealer = WifiSealer(SealedSession(bytes(32), bytes(12), b""), use_aes=True)
    assert sealer.algorithm == "AES-GCM"
    assert sealer._seal_raw(bytes(16)) == GCM14_CT + GCM14_TAG
    assert sealer._open_raw(GCM14_CT + GCM14_TAG) == bytes(16)


