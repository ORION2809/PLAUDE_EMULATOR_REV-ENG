# --- the ciphertext heuristic ----------------------------------------------------


def _frame_with_type_word(word: int) -> bytes:
    return bytes.fromhex("08000001") + word.to_bytes(2, "little") + b"\x00\x00"


def test_heuristic_boundary_is_strictly_greater_than_200():
    assert CIPHERTEXT_TYPE_THRESHOLD == 200
    assert looks_encrypted(_frame_with_type_word(200)) is False
    assert looks_encrypted(_frame_with_type_word(201)) is True
    assert looks_encrypted(_frame_with_type_word(101)) is False       # highest real type
    assert looks_encrypted(_frame_with_type_word(0xFFFF)) is True
    assert looks_encrypted(_frame_with_type_word(0xFFFF)[:7]) is False  # "Message too short" path
    # a real plaintext PDU is never mistaken for ciphertext
    assert looks_encrypted(HeartbeatPong(1).encode()) is False


