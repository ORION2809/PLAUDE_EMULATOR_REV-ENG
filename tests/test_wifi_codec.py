def test_heartbeat_pong_pdu_bytes_are_hand_computed():
    # {"stamp":1700000000} is 20 bytes; total 28 = 0x1c; type 3; jsonSize 0x14.
    wire = HeartbeatPong(1700000000).encode()
    assert wire == bytes.fromhex("1c000001" "0300" "1400") + b'{"stamp":1700000000}'
    pdu = parse_pdu(wire)
    assert (pdu.total_size, pdu.pdu_version, pdu.msg_type, pdu.json_size) == (28, 1, 3, 20)
    assert pdu.tail == b""
    assert pdu.json == {"stamp": 1700000000}


def test_handshake_request_pads_token_to_32_with_ascii_zero():
    wire = HandshakeRequest("abc", 7).encode()
    body = b'{"token":"abc' + b"0" * 29 + b'","stamp":7}'
    assert len(body) == 54
    assert wire == bytes.fromhex("3e000001" "0100" "3600") + body
    req = decode_for_device(wire)
    assert isinstance(req, HandshakeRequest)
    assert req.token == "abc" + "0" * 29 and req.stamp == 7


def test_pad_matches_k3_below_32_and_diverges_above():
    """padEnd never truncates; k3 does. Same rule up to 32 characters."""
    tok = "SYNTHETIC-TOKEN-0123456789ABCDEF"  # exactly 32
    assert pad_wifi_token(tok) == tok
    assert pad_wifi_token("x") == "x" + "0" * 31
    k3_token = build_k3("x", port_version=9)[6:].decode()
    assert k3_token == pad_wifi_token("x")
    longer = tok + "ZZ"
    assert pad_wifi_token(longer) == longer               # 34 chars, untouched
    assert build_k3(longer, port_version=9)[6:].decode() == tok  # k3 truncates


def test_pdu_with_tail_counts_the_tail_in_total_size():
    wire = FileSyncContent(session=5, offset=0, data=b"ab", last=True).encode()
    body = b'{"session":5,"offset":0,"length":2,"last":1}'
    assert len(body) == 44
    assert wire == bytes.fromhex("36000001" "0d00" "2c00") + body + b"ab"
    pdu = parse_pdu(wire, strict_total=True)
    assert pdu.tail == b"ab"


def test_parse_pdu_guards_mirror_the_sdk_messages():
    with pytest.raises(ValueError, match="Data too short for header"):
        parse_pdu(b"\x07\x00\x00\x01\x03\x00\x00")
    # header says 20 JSON bytes but only 3 follow
    with pytest.raises(ValueError, match="Data too short for JSON content"):
        parse_pdu(bytes.fromhex("0b000001" "0300" "1400") + b"{}x")
    # negative jsonSize (s16) is also "too short"
    with pytest.raises(ValueError, match="Data too short for JSON content"):
        parse_pdu(bytes.fromhex("08000001" "0300" "ffff"))
    # totalSize is not checked unless asked
    lying = bytes.fromhex("ff000001" "0300" "0200") + b"{}"
    assert parse_pdu(lying).total_size == 0xFF
    with pytest.raises(ValueError, match="totalSize"):
        parse_pdu(lying, strict_total=True)


def test_unparseable_json_yields_defaults_not_an_error():
    """BaseWifiResponse swallows JSONException; getters return their defaults."""
    wire = pack_pdu(MSG_HANDSHAKE, b"not json")
    pdu = parse_pdu(wire)
    assert pdu.json is None
    rsp = HandshakeResponse.from_pdu(pdu)
    assert rsp.status == -1 and rsp.session == ""


