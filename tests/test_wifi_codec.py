def test_file_sync_content_tail_is_accepted_only_when_it_matches_length():
    good = FileSyncContent(1, 0, b"xyz", last=False).encode()
    assert decode_for_phone(good).data == b"xyz"
    # declared length 3 but 4 bytes follow -> getFileData returns empty
    bad = pack_pdu(MSG_FILE_SYNC_CONTENT, {"session": 1, "offset": 0, "length": 3, "last": 0}, b"wxyz")
    assert decode_for_phone(bad).data == b""
    # an empty last frame is a legitimate terminator
    fin = FileSyncContent(1, 10, b"", last=True).encode()
    parsed = decode_for_phone(fin)
    assert parsed.last is True and parsed.data == b"" and parsed.length == 0


def test_heartbeat_ping_emits_both_battery_spellings_and_int_charging():
    j = HeartbeatPing(87, True, 4100).to_json()
    assert j == {"battery": 87, "volume": 87, "charging": 1, "voltage": 4100}
    # a proto-path pen that only sent "volume" still parses
    only_volume = pack_pdu(MSG_HEARTBEAT, {"volume": 42, "charging": 0, "voltage": 1})
    ping = HeartbeatPing.from_pdu(parse_pdu(only_volume))
    assert ping.battery == 42 and ping.charging is False
    # a JSON boolean is NOT coerced by optInt: charging stays false
    boolean = pack_pdu(MSG_HEARTBEAT, {"battery": 1, "charging": True, "voltage": 1})
    assert HeartbeatPing.from_pdu(parse_pdu(boolean)).charging is False


def test_heartbeat_pong_accepts_the_empty_proto_form():
    assert HeartbeatPong.from_pdu(parse_pdu(pack_pdu(MSG_HEARTBEAT, {}))).stamp is None
    assert HeartbeatPong.from_pdu(parse_pdu(HeartbeatPong(9).encode())).stamp == 9


